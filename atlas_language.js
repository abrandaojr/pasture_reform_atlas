const _atlasOriginalText = new WeakMap();
const _atlasOriginalAttr = new WeakMap();
const _atlasReverseText = new Map(Object.entries(UI_EN).map(([pt,en])=>[en,pt]));
let _atlasTranslating = false;
let _atlasProfileCode = '';
const _atlasTranslationExcluded='script,style,#language-switch,[translate="no"],#brand-name,#brand-eyebrow,#atlas-ribbon,#data-status';
function atlasTranslateString(value){
  const trimmed=value.trim();
  if(ATLAS_LANGUAGE!=='en') return _atlasReverseText.has(trimmed)?value.replace(trimmed,_atlasReverseText.get(trimmed)):value;
  if(UI_EN[trimmed]) return value.replace(trimmed,UI_EN[trimmed]);
  let out=value;
  UI_EN_PARTS.forEach(([pt,en])=>{out=out.split(pt).join(en)});
  return out;
}
function atlasTranslateNode(root=document.body){
  if(!root||_atlasTranslating)return;
  if(root.nodeType===Node.TEXT_NODE&&root.parentElement?.closest(_atlasTranslationExcluded))return;
  if(root.nodeType===Node.ELEMENT_NODE&&root.closest(_atlasTranslationExcluded))return;
  _atlasTranslating=true;
  try{
    const nodes=[];
    if(root.nodeType===Node.TEXT_NODE)nodes.push(root);
    else{
      const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT,{acceptNode:n=>n.parentElement&&!n.parentElement.closest(_atlasTranslationExcluded)?NodeFilter.FILTER_ACCEPT:NodeFilter.FILTER_REJECT});
      let n;while((n=walker.nextNode()))nodes.push(n);
    }
    nodes.forEach(n=>{
      let state=_atlasOriginalText.get(n);
      // A renderer may reuse an existing text node. Do not restore stale content.
      if(!state||n.nodeValue!==state.rendered)state={source:n.nodeValue,rendered:n.nodeValue};
      const rendered=atlasTranslateString(state.source);
      if(n.nodeValue!==rendered)n.nodeValue=rendered;
      state.rendered=rendered;_atlasOriginalText.set(n,state);
    });
    const elements=root.nodeType===Node.ELEMENT_NODE?[root,...root.querySelectorAll('*')]:[];
    elements.forEach(el=>{
      if(el.closest(_atlasTranslationExcluded))return;
      if(el.tagName==='OPTION'&&!el.hasAttribute('value'))el.setAttribute('value',_atlasOriginalText.get(el.firstChild)?.source?.trim()||el.textContent.trim());
      let saved=_atlasOriginalAttr.get(el);if(!saved){saved={};_atlasOriginalAttr.set(el,saved)}
      for(const attr of ['placeholder','aria-label','title','data-help','alt']){
        if(!el.hasAttribute(attr))continue;
        const current=el.getAttribute(attr);let state=saved[attr];
        if(!state||current!==state.rendered)state={source:current,rendered:current};
        const rendered=atlasTranslateString(state.source);
        if(current!==rendered)el.setAttribute(attr,rendered);
        state.rendered=rendered;saved[attr]=state;
      }
    });
  }finally{_atlasTranslating=false;}
}
const _atlasTranslationObserver=new MutationObserver(changes=>{
  for(const change of changes){
    if(change.type==='childList')change.addedNodes.forEach(atlasTranslateNode);
    else atlasTranslateNode(change.target);
  }
});
function updateAtlasTranslations(){
  document.querySelectorAll('option:not([value])').forEach(o=>o.setAttribute('value',o.textContent.trim()));
  atlasTranslateNode(document.body);
  document.dispatchEvent(new CustomEvent('atlaslanguagechange',{detail:{language:ATLAS_LANGUAGE}}));
}
